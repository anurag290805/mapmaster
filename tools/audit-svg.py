#!/usr/bin/env python3
"""Read-only SVG/data inventory; run from project root. Not a browser hit test."""
import collections, json, pathlib, subprocess, xml.etree.ElementTree as ET
js = r'''const fs=require('fs'),vm=require('vm');let c=vm.createContext({});let d=fs.readFileSync('js/data.js','utf8');let u=fs.readFileSync('js/ui.js','utf8');let a=u.slice(u.indexOf('const SVG_ALIASES ='),u.indexOf('// Reverse map:'));vm.runInContext(d+'\n'+a+'\nthis.out={MAPS,FLAGS,CAPITALS,MAP_SUPPORT,SVG_ALIASES}',c);console.log(JSON.stringify(c.out));'''
data=json.loads(subprocess.check_output(['node','-e',js],text=True))
alias=data['SVG_ALIASES']
root=pathlib.Path('.')
print('# Static SVG and geography inventory\n\nGenerated by `python3 tools/audit-svg.py`. Counts describe static XML attributes and the application alias table; they do not establish rendering, hit-testing or keyboard access. America fallback files are inspected only as assets; configured paths remain broken.\n')
details=[]
print('| Scope | Configured path | Regions | Missing click-name match | Multiple path matches | Duplicate IDs | Flags | Capitals |')
print('|---|---|---:|---:|---:|---:|---:|---:|')
for key,m in data['MAPS'].items():
 p=root/m['svg']; exists=p.is_file()
 if not exists:p=root/m['svg'].replace(' ','_')
 if not p.is_file():
  print(f'| {key} | MISSING | {len(m["regions"])} | unknown | unknown | unknown | — | — |');continue
 tree=ET.parse(p); els=list(tree.iter()); ids=collections.Counter(e.get('id') for e in els if e.get('id')); dup={k:v for k,v in ids.items() if v>1}
 matches=collections.defaultdict(list)
 for e in els:
  if e.tag.split('}')[-1]!='path':continue
  raw=next((e.get(a) for a in ('aria-label','name','data-name','title','id') if e.get(a)),None)
  if not raw:
   title=next((x.text.strip() for x in e if x.tag.split('}')[-1]=='title' and x.text),None);raw=title
  if raw:matches[alias.get(raw.strip(),raw)].append(raw)
 missing=[r for r in m['regions'] if r not in matches]
 multi=[r for r in m['regions'] if len(matches[r])>1]
 caps=data['CAPITALS'].get(key,{})
 flags=[r for r in m['regions'] if r in data['FLAGS']]; capitals=[r for r in m['regions'] if r in caps]
 print(f'| {key} | {"present" if exists else "MISSING; asset inspected"} | {len(m["regions"])} | {len(missing)} | {len(multi)} | {len(dup)} | {len(flags)} | {len(capitals)} |')
 if missing or multi or dup:
  details.append(f'- **{key}**: missing={json.dumps(missing,ensure_ascii=False)}; multiple={json.dumps(multi,ensure_ascii=False)}; duplicate IDs={json.dumps(dup,ensure_ascii=False)}')
 if data['MAP_SUPPORT'].get(key,{}).get('flag') or data['MAP_SUPPORT'].get(key,{}).get('capital'):
  details.append(f'- **{key} data gaps**: flags={json.dumps([r for r in m["regions"] if r not in data["FLAGS"]],ensure_ascii=False) if data["MAP_SUPPORT"].get(key,{}).get("flag") else "disabled"}; capitals={json.dumps([r for r in m["regions"] if r not in caps],ensure_ascii=False) if data["MAP_SUPPORT"].get(key,{}).get("capital") else "disabled"}')
print('\n## Details\n')
print('\n'.join(details))
print('\nCounts match path element names resolved using getRegionName precedence; click events can also bubble from other elements, and alias translation is global. Multiple path matches may be legitimate multipart geometry; the application coloring function returns one element. Name matches are not proof of accessible, visible or clickable targets. Flags on subdivision maps are disabled and incidental counts are not coverage requirements.\n')
print('## CP01 consolidation\n\nConsolidation: this generated static report applies to the selected audited files; actual target hit-testing is deferred to CP05. See BASELINE_COMPARISON.md for their provenance.')
